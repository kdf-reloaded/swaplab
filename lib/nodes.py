"""KDF nodes as Docker containers: run directories, MM2.json, compose files, lifecycle.

Every node has a persistent run directory run/<name>/ (mode 0700) mounted at /kdf:
    MM2.json   0600, generated by the harness (passphrase, rpc_password, netid, seednodes)
    coins      copy of the scenario's coins file
    DB/        KDF database; never deleted by the harness (a failed swap may still need it)
    logs/      one KDF log per run id (MM_LOG)
The binary is bind-mounted read-only at /usr/local/bin/kdf; nothing is baked into the image.
"""
import hashlib
import json
import os
import secrets as _rnd
import shutil
import socket
import string
import subprocess

from . import wallets
from .kdfrpc import Kdf

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RUN = os.path.join(ROOT, "run")
IMAGE = "swaplab/kdf-runtime:debian12"
RPC_IN_CONTAINER = 7783


def sh(*cmd, check=True, capture=True, env=None):
    r = subprocess.run(cmd, check=False, text=True, env=env,
                       stdout=subprocess.PIPE if capture else None,
                       stderr=subprocess.STDOUT if capture else None)
    if check and r.returncode:
        raise RuntimeError(f"{' '.join(cmd)} failed ({r.returncode}): {(r.stdout or '')[-2000:]}")
    return r.stdout or ""


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def strong_password():
    """Satisfies KDF's password policy: 8-32 chars, upper, lower, digit, special, no triples."""
    alphabet = string.ascii_letters + string.digits
    while True:
        core = "".join(_rnd.choice(alphabet) for _ in range(20))
        p = f"S{core}-9a"
        if all(p[i] != p[i + 1] or p[i] != p[i + 2] for i in range(len(p) - 2)):
            return p


def port_free(port, host="127.0.0.1"):
    with socket.socket() as s:
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)  # ignore TIME_WAIT of a previous run
        try:
            s.bind((host, port))
            return True
        except OSError:
            return False


def ensure_image(rebuild=False):
    if not rebuild and sh("docker", "images", "-q", IMAGE).strip():
        return
    sh("docker", "build", "-t", IMAGE, "-f", os.path.join(ROOT, "docker", "Dockerfile"),
       os.path.join(ROOT, "docker"), capture=False)


class Node:
    """One KDF process in one container. role: seed | maker | taker | wallet."""

    def __init__(self, role, flavor, binary, netid, ip, host_port, wallet=None, coins_file=None,
                 seednodes=(), disable_p2p=False):
        self.role, self.flavor, self.binary, self.netid = role, flavor, binary, netid
        self.ip, self.host_port, self.wallet = ip, host_port, wallet
        self.coins_file, self.seednodes, self.disable_p2p = coins_file, list(seednodes), disable_p2p
        who = f"seed-{flavor}" if role == "seed" else f"{flavor}-{wallet}"
        self.name = f"{netid}-{who}"
        self.dir = os.path.join(RUN, self.name)
        self.service = role

    # ----------------------------------------------------------------- run directory
    def _secret_passphrase(self):
        if self.role == "seed":  # the seed node only needs a stable p2p identity, not funds
            p = os.path.join(self.dir, "seed-identity")
            if not os.path.exists(p):
                fd = os.open(p, os.O_WRONLY | os.O_CREAT, 0o600)
                with os.fdopen(fd, "w") as f:
                    f.write(wallets.new_mnemonic())
            with open(p) as f:
                return f.read().strip(), False
        w = wallets.load(self.wallet)
        return w["passphrase"], bool(w.get("enable_hd"))

    def prepare(self, gui):
        new = not os.path.exists(self.dir)
        os.makedirs(os.path.join(self.dir, "logs"), exist_ok=True)
        os.chmod(self.dir, 0o700)
        if new and self.role != "seed" and self.wallet:
            wd = wallets.load(self.wallet).get("wallet_dir")
            if wd:  # imported wallet dir: its copy seeds this node's DB exactly once
                shutil.copytree(os.path.join(ROOT, wd), os.path.join(self.dir, "DB"))
        os.makedirs(os.path.join(self.dir, "DB"), exist_ok=True)
        old = self.mm2() if os.path.exists(self.mm2_path) else {}
        passphrase, hd = self._secret_passphrase()
        cfg = {
            "gui": gui, "netid": self.netid, "passphrase": passphrase,
            "rpc_password": old.get("rpc_password") or strong_password(),
            "allow_weak_password": True,  # a BIP39 mnemonic never passes KDF's password policy
            "rpcport": RPC_IN_CONTAINER, "rpcip": "0.0.0.0",
            "rpc_local_only": False,  # reachable only through 127.0.0.1:<host_port> on the host
            "dbdir": "/kdf/DB", "myipaddr": self.ip,
            "i_am_seed": self.role == "seed",
        }
        if self.role == "seed":
            cfg.update(is_bootstrap_node=True, disable_p2p=False, seednodes=[])
        elif self.disable_p2p:
            cfg.update(disable_p2p=True)
        else:
            cfg.update(seednodes=self.seednodes, disable_p2p=False)
        if hd:
            cfg["enable_hd"] = True
        fd = os.open(self.mm2_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            json.dump(cfg, f, indent=1)
        os.chmod(self.mm2_path, 0o600)
        shutil.copyfile(self.coins_file, os.path.join(self.dir, "coins"))

    @property
    def mm2_path(self):
        return os.path.join(self.dir, "MM2.json")

    def mm2(self):
        with open(self.mm2_path) as f:
            return json.load(f)

    def rpc(self):
        return Kdf(self.name, f"http://127.0.0.1:{self.host_port}/", self.mm2()["rpc_password"])

    def log_path(self, run_id):
        return os.path.join(self.dir, "logs", f"{run_id}.log")

    def secrets(self):
        try:
            c = self.mm2()
            return [c.get("passphrase"), c.get("rpc_password")]
        except (OSError, ValueError):
            return []

    def describe(self):
        return {"role": self.role, "flavor": self.flavor, "wallet": self.wallet, "netid": self.netid,
                "run_dir": os.path.relpath(self.dir, ROOT), "ip": self.ip, "host_port": self.host_port,
                "binary": self.binary, "binary_sha256": sha256(self.binary)}


# --------------------------------------------------------------------------- compose
class Stack:
    """The containers of one run: a compose project with its own bridge network."""

    def __init__(self, project, subnet, nodes, run_id):
        self.project, self.subnet, self.nodes, self.run_id = project, subnet, nodes, run_id
        self.file = os.path.join(RUN, f"compose-{project}.yml")

    def write(self):
        uid, gid = os.getuid(), os.getgid()
        lines = [f"# generated by swaplab.py for run {self.run_id}; contains no secrets",
                 f"name: {self.project}", "services:"]
        for n in self.nodes:
            lines += [
                f"  {n.service}:",
                f"    image: {IMAGE}",
                f"    container_name: {self.project}-{n.service}",
                f'    user: "{uid}:{gid}"',
                "    environment:",
                f"      MM_LOG: /kdf/logs/{self.run_id}.log",
                "    volumes:",
                f"      - {n.dir}:/kdf",
                f"      - {os.path.abspath(n.binary)}:/usr/local/bin/kdf:ro",
                "    ports:",
                f'      - "127.0.0.1:{n.host_port}:{RPC_IN_CONTAINER}"',
                "    networks:",
                "      mesh:",
                f"        ipv4_address: {n.ip}",
                "    stop_grace_period: 30s",
            ]
        lines += ["networks:", "  mesh:", "    driver: bridge", "    ipam:",
                  "      config:", f"        - subnet: {self.subnet}", ""]
        with open(self.file, "w") as f:
            f.write("\n".join(lines))

    def compose(self, *args, check=True):
        return sh("docker", "compose", "-p", self.project, "-f", self.file, *args, check=check)

    def up(self, wait_seed=None):
        """Start the seed first and wait until it answers (wait_seed: callable), then the rest.
        Some flavors (Komodo 2.x) dial their seednodes once at start-up and throttle retries, so a
        node started before the seed listens may never connect."""
        self.write()
        seeds = [n.service for n in self.nodes if n.role == "seed"]
        rest = [n.service for n in self.nodes if n.role != "seed"]
        if seeds and wait_seed:
            self.compose("up", "-d", "--force-recreate", *seeds)
            wait_seed()
            self.compose("up", "-d", "--force-recreate", *rest)
        else:
            self.compose("up", "-d", "--force-recreate")

    def down(self):
        for n in self.nodes:  # graceful KDF stop first, so the DB is closed cleanly
            try:
                n.rpc().stop()
            except Exception:  # noqa
                pass
        self.compose("down", "--timeout", "30", check=False)

    def running(self):
        out = self.compose("ps", "--format", "json", check=False)
        rows = []
        for line in out.splitlines():
            line = line.strip()
            if line.startswith("{"):
                rows.append(json.loads(line))
            elif line.startswith("["):
                rows += json.loads(line)
        return [r.get("Service") for r in rows if r.get("State") == "running"]


def running_projects():
    out = sh("docker", "ps", "--format", "{{.Label \"com.docker.compose.project\"}}", check=False)
    return sorted({p for p in out.split() if p.startswith("swaplab-")})
